const HEIGHT = 6;
const GAP = " ";

function renderLine(line) {
  line = line.toUpperCase();
  let rows = Array(HEIGHT).fill("");
  [...line].forEach((ch, index) => {
    let glyph = FONT[ch] || FONT["?"];
    let width = Math.max(...glyph.map(x => x.length));
    for (let r = 0; r < HEIGHT; r++) {
      let linePart = glyph[r] || "";
      rows[r] += linePart.padEnd(width, " ");
      if (index < line.length - 1) rows[r] += GAP;
    }
  });
  return rows;
}

function render(text) {
  // Zamień dosłowne "\n" na prawdziwe znaki nowej linii
  text = text.replace(/\\n/g, '\n');
  const lines = text.split('\n');
  const allRows = [];
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const rows = renderLine(line);
    allRows.push(...rows);
  }
  return allRows.join('\n');
}

function generateArt() {
  document.getElementById("output").textContent = render(document.getElementById("inputText").value);
}

function copyOutput() {
  navigator.clipboard.writeText(document.getElementById("output").textContent);
}

function saveToFile() {
  const content = document.getElementById("output").textContent;
  const blob = new Blob([content], { type: "text/plain;charset=utf-8" });
  const a = document.createElement("a");
  a.href = URL.createObjectURL(blob);
  a.download = "output.txt";
  a.click();
  URL.revokeObjectURL(a.href);
}